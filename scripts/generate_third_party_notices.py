# to accompany the LGPL text, and the LGPL-3-or-GPL-2 libraries above make GPL-2 relevant too, so
# all four are carried rather than the two an LGPL-2.1-only bundle would need.
LICENSE_TEXTS = (
    ("LGPL-2.1", "licenses/LGPL-2.1.txt"),
    ("LGPL-3", "licenses/LGPL-3.txt"),
    ("GPL-2", "licenses/GPL-2.txt"),
    ("GPL-3", "licenses/GPL-3.txt"),
)


def _dpkg(args: list[str]) -> str:
    """Run a dpkg query and return stdout, or raise with a message naming what failed."""
    result = subprocess.run(args, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"{' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def scan_appdir(appdir: Path) -> list[dict]:
    """Enumerate a built AppDir's bundled libraries, grouped by Ubuntu SOURCE package.

    Build host only. For each `.so` under the AppDir's library directory: find the same file on the
    host, resolve the symlink (dpkg records the real file, not the SONAME link), ask `dpkg -S` which
    binary package owns it, then `dpkg-query` for that package's source name and source version.

    Grouped by source package rather than per-library because that is the unit a licence attaches
    to and the unit `apt-get source` takes — a per-.so table would repeat the same four fields
    eight times for gst-plugins-base and still not tell a recipient what to fetch.

    The source VERSION is carried, not just the name. Without it the §6(d) offer is unanswerable:
    "gnutls28" identifies a project, "gnutls28 3.8.3-1.1ubuntu3.6" identifies the code that is
    actually inside the binary.
    """
    lib_dir = appdir / APPDIR_LIB_SUBPATH
    if not lib_dir.is_dir():
        raise SystemExit(
            f"{lib_dir} does not exist — run packaging/build-appimage.sh first, or pass "
            f"--appdir. This mode enumerates a BUILT AppDir; it cannot work from sources."
        )

    by_source: dict[str, dict] = {}
    unmapped: list[str] = []
    for shipped in sorted(p for p in lib_dir.iterdir() if p.is_file() and ".so" in p.name):
        host_path = HOST_LIB_DIR / shipped.name
        if not host_path.exists():
            # Plugin backends live in a subdirectory of the host library dir (libproxy's, for
            # instance) even though the build flattens them into the AppDir.
            candidates = sorted(HOST_LIB_DIR.rglob(shipped.name))
            if not candidates:
                unmapped.append(shipped.name)
                continue
            host_path = candidates[0]

        owner = _dpkg(["dpkg", "-S", os.path.realpath(host_path)]).split(":")[0].strip()
        source, _, version = _dpkg(
            ["dpkg-query", "-W", "-f=${source:Package}\t${source:Version}", owner]
        ).partition("\t")
        entry = by_source.setdefault(
            source, {"source": source, "version": version, "binary_packages": [], "libraries": []}
        )
        if owner not in entry["binary_packages"]:
            entry["binary_packages"].append(owner)
        entry["libraries"].append(shipped.name)

    if unmapped:
        raise SystemExit(
            "these bundled libraries could not be traced to a host file, so their source package "
            "is unknown:\n  " + "\n  ".join(unmapped) + "\nA notice missing them would be "
            "incomplete; investigate rather than skipping them."
        )

    missing = sorted(s for s in by_source if s not in LICENSE_SUMMARY)
    if missing:
        raise SystemExit(
            "no LICENSE_SUMMARY entry for these source packages:\n  " + "\n  ".join(missing) +
            "\nRead /usr/share/doc/<binary-package>/copyright for each and add an entry. Do not "
            "trust the `Files: *` stanza without checking which files it actually covers."
        )

    records = []
    for source in sorted(by_source):
        entry = by_source[source]
        entry["binary_packages"] = sorted(entry["binary_packages"])
        entry["libraries"] = sorted(entry["libraries"])
        entry["license"] = LICENSE_SUMMARY[source]
        records.append(entry)
    return records


def refresh_system_libs(appdir: Path, out_path: Path) -> int:
    """Rewrite the committed system-library JSON from a built AppDir. Build host only."""
    records = scan_appdir(appdir)
    total = sum(len(r["libraries"]) for r in records)
    payload = {
        "//": (
            "Generated by scripts/generate_third_party_notices.py --refresh-system-libs on the "
            "Ubuntu 24.04 AppImage build host. Describes the libraries bundled in the Linux "
            "AppImage only. Regenerate after any change to what packaging/build-appimage.sh "
            "copies, or after a rebuild on an updated host."
        ),
        "distribution": "Ubuntu 24.04 (noble)",
        "library_count": total,
        "packages": records,
    }
    # sort_keys plus a trailing newline: the file is committed, so its diff should show only what
    # actually changed on the host.
    out_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {out_path}: {total} libraries from {len(records)} source packages")
    print("Now re-run this script without --refresh-system-libs to regenerate the notice.")
    return 0


def load_system_libs() -> dict:
    """The committed host-derived system-library data.

    Read rather than recomputed: the data can only be produced on the build host, and this script
    must also run on a laptop and in CI. A missing file is an error rather than an empty section —
    silently omitting the LGPL libraries is the exact failure this file exists to prevent.
    """
    if not SYSTEM_LIBS_PATH.exists():
        raise SystemExit(
            f"{SYSTEM_LIBS_PATH} is missing. It is committed, and holds the AppImage's system "
            f"library inventory. Restore it from git, or regenerate it on the Ubuntu build host "
            f"with:\n  python3 scripts/generate_third_party_notices.py --refresh-system-libs"
        )
    return json.loads(SYSTEM_LIBS_PATH.read_text(encoding="utf-8"))


