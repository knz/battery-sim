def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUTPUT_PATH,
                        help=f"where to write the notice (default {OUTPUT_PATH})")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the notice to stdout without writing anything")
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the file on disk differs from freshly generated "
                             "output (for CI); writes nothing. Note that this validates sections "
                             "1 and 2 against the repository, and section 3 only against the "
                             "committed JSON — it cannot tell whether that JSON is current")
    parser.add_argument("--refresh-system-libs", action="store_true",
                        help="BUILD HOST ONLY: enumerate a built AppDir with dpkg and rewrite "
                             "packaging/appimage-system-libraries.json. Needs Ubuntu 24.04 and "
                             "dist/AppDir; does not write the notice")
    parser.add_argument("--appdir", type=Path, default=DEFAULT_APPDIR,
                        help=f"AppDir to enumerate with --refresh-system-libs "
                             f"(default {DEFAULT_APPDIR})")
    args = parser.parse_args(argv)

    if args.dry_run and args.check:
        parser.error("--dry-run and --check are mutually exclusive")

    # The refresh is a separate job with a separate input, so it returns before any rendering:
    # it deliberately does NOT go on to rewrite the notice, because a build host and a synced
    # Python environment are not the same machine and the notice needs both.
    if args.refresh_system_libs:
        return refresh_system_libs(args.appdir, SYSTEM_LIBS_PATH)

    notice, warnings = render()
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    if args.dry_run:
        sys.stdout.write(notice)
        return 0

    if args.check:
        if not args.out.exists():
            print(f"FAIL: {args.out} does not exist; run this script without --check.")
            return 1
        if args.out.read_text(encoding="utf-8") != notice:
            print(f"FAIL: {args.out} is out of date with respect to the repository.")
            print("Regenerate it with:")
            print("  uv run python scripts/generate_third_party_notices.py")
            return 1
        print(f"ok: {args.out.name} is up to date")
        return 0

    args.out.write_text(notice, encoding="utf-8")
    system = load_system_libs()
    print(f"wrote {args.out} ({notice.count(chr(10))} lines, {len(runtime_packages())} Python "
          f"packages, {system['library_count']} system libraries from "
          f"{len(system['packages'])} source packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
