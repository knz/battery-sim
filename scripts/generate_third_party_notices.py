#!/usr/bin/env python3
"""Generate THIRD-PARTY-NOTICES.md, the attribution file for third-party code we redistribute.

The project itself is AGPL-3.0-only (see LICENSE), but what a user receives from a release is not
only our code. Three separate bodies of third-party code travel with it, each arriving by a
different route and each needing a different kind of evidence, which is why this script has three
sections rather than one list:

  1. **Vendored browser assets** — files committed in this repository and served to the browser:
     `app/static/vendor/plotly.min.js` (plotly.js, MIT) and `app/static/app.css`, which is the
     *compiled output* of Tailwind CSS and daisyUI (both MIT). app.css is generated but committed,
     so it ships in every distribution form including a plain `git clone`.

  2. **Python runtime dependencies** — the wheels PyInstaller freezes into the macOS/Windows
     bundles and the Linux AppImage. The set is the `[project].dependencies` closure from
     pyproject.toml resolved through uv.lock; the `dev` dependency-group (pytest, playwright,
     httpx) is deliberately excluded because it is not bundled.

  3. **System libraries from the Debian/Ubuntu stack** — copied off the build host into the Linux
     AppImage by packaging/build-appimage.sh. This is the section with real obligations attached.
     The measured contents of a built AppDir are 119 shared libraries from 85 Ubuntu 24.04 source
     packages, and the licences are genuinely mixed: much of it is LGPL-2.1+ (GTK, GLib,
     gdk-pixbuf, Pango, WebKitGTK's core, libsoup, at-spi2), some is LGPL-3-or-GPL-2 (Nettle, GMP,
     libunistring, libidn2 — reached through GIO's GnuTLS module), and a large remainder is
     permissive (zlib, libpng, HarfBuzz, ICU, SQLite, fontconfig, OpenSSL …). See the "obligations"
     note below for what follows from that.

## Two generation paths, and only one of them is checkable

The important structural fact about this script: sections 1 and 2 can be regenerated anywhere from
the repository, and section 3 cannot.

**Sections 1 and 2 — repo-derived, and what `--check` actually validates.** The Plotly version and
copyright come from the banner comment at the top of the minified bundle, the Tailwind version from
the banner in app.css, the Tailwind/daisyUI versions from package-lock.json, the Python package set
from pyproject.toml resolved through uv.lock, and each Python licence from installed distribution
metadata via `importlib.metadata` (`License-Expression`, else `License`, else `License ::`
classifiers). Nothing reaches the network.

**Section 3 — host-derived, and NOT validated by `--check`.** The libraries are not in this
repository. They exist only on the Ubuntu 24.04 machine that runs build-appimage.sh, and the set
that ships is the transitive `ldd` closure of that script's LIB_ROOTS — the roots are 6 files, the
closure is 119. Enumerating it needs a built `dist/AppDir`, plus `dpkg -S`, `dpkg-query` and
`/usr/share/doc/*/copyright`, none of which exist on a developer checkout or a generic CI runner.

So section 3 is generated by a separate pass, `--refresh-system-libs`, run on the build host; it
writes `packaging/appimage-system-libraries.json`, which is committed. Ordinary runs of this script
read that JSON and render it. `--check` therefore verifies only that the committed notice matches
what sections 1 and 2 plus the *committed* JSON produce — it cannot tell whether the JSON itself
still describes the current build host. The generated file says so in as many words. Claiming
otherwise would be the overclaim this whole file exists to avoid.

## The obligations section 3 exists to discharge

LGPL-2.1 §6 and LGPL-3 §4 permit distributing a work that links LGPL libraries, provided the
recipient is told which libraries are included, is given their corresponding source, and can
relink. AGPL-3.0-only is compatible with both, so this is a notice obligation, not a conflict.
Three specifics shape what the generated file has to say:

  * **Four licence texts, not two.** LGPL-3 §4(b) requires the GNU GPL text alongside the LGPL
    text; the same is true of the LGPL-3-or-GPL-2 libraries. `licenses/` therefore carries verbatim
    LGPL-2.1, LGPL-3, GPL-2 and GPL-3.

  * **§6(b) is not available to us.** That option — rely on a copy of the library already on the
    user's machine — does not apply to an AppImage, whose entire point is to carry its own. The
    route taken is §6(d): offer equivalent source access from the same place the binary is
    distributed. That is why each entry carries a source-package NAME and VERSION rather than only
    a project homepage: those two strings are what make the offer answerable.

  * **libwebkit2gtk-4.1.so.0 is modified.** build-appimage.sh binary-patches two .rodata path
    strings in the copied library. §6(a) asks for corresponding source "including whatever changes
    were used", so pointing at Ubuntu's archive alone is incomplete; the notice states the
    modification and points at the patching code in our own published source.

## Debian copyright metadata is not reliably machine-readable

Section 3 records the source package and version for every library and points at the copyright
file, rather than trying to distil one licence string per package automatically. Several packages
here (cairo, fontconfig, pixman, libxslt, gnutls, libgcrypt, gstreamer, libjpeg-turbo, libtasn1)
have non-DEP-5 copyright files that a parser reads as blank. Worse, the `Files: *` stanza is
actively misleading for three of them — webkit2gtk declares BSD-2-clause though its core is
LGPL-2.1+, gobject-introspection declares GPL-2+ though the shipped library is LGPL-2+, and libidn2
declares GPL-3+ though the shipped library is LGPL-3+/GPL-2+. LICENSE_SUMMARY below is therefore a
reviewed-by-hand summary per source package, and `--refresh-system-libs` reports any package it has
no entry for instead of guessing.

Host-provided libraries carry no notice and are absent by construction: glibc and the loader,
libstdc++, libgcc_s, the GL/EGL/DRI stack and the X11/Wayland client libraries are excluded by
build-appimage.sh (HOST_PROVIDED in packaging/check-appdir-closure.py is the authoritative list),
and LGPL-2.1 §6 exempts major components of the operating system in any case.

## Usage

    uv run python scripts/generate_third_party_notices.py             # write the notice
    uv run python scripts/generate_third_party_notices.py --dry-run   # print it, write nothing
    uv run python scripts/generate_third_party_notices.py --check     # CI: fail if stale

    # on the Ubuntu 24.04 build host, after packaging/build-appimage.sh has produced dist/AppDir:
    python3 scripts/generate_third_party_notices.py --refresh-system-libs

Run the first three under `uv run` (or any synced environment): the Python licences are read from
installed distributions. The last needs only the stdlib and dpkg, which is why it is written to run
under the system python3 on a build host.

Output is deterministic — sorted, no timestamps, no host paths, and no value that depends on which
platform generated it — so `--check` tests staleness rather than environment.

Main items:
    read_plotly_banner() / read_tailwind_banner() / npm_versions()
                            vendored-asset versions, read back out of the shipped files.
    runtime_packages()      pyproject.toml + uv.lock → bundled distribution name → version.
    package_license()       one installed distribution → its licence, via importlib.metadata.
    PLATFORM_ONLY_LICENSES  licences for the Python packages installed on one platform only.
    LICENSE_SUMMARY         reviewed licence summary per Ubuntu source package (see above).
    scan_appdir()           build host only: dist/AppDir → the system-library records.
    render()                (the whole notice, warnings for stderr).
    main(argv)              CLI: render and write / print / compare, or refresh the host data.
"""

