# ── vendored browser assets ───────────────────────────────────────────────────

def read_plotly_banner() -> tuple[str, str]:
    """(version, copyright line) from the banner comment plotly.min.js carries at line 1.

    Read from the file rather than hardcoded so that dropping in a new plotly build updates the
    notice on the next run. Raises if the banner is not in the expected shape: a silently empty
    version would produce an attribution that names no version at all, which is worse than a
    failed script run.
    """
    head = PLOTLY_PATH.read_text(encoding="utf-8", errors="replace")[:2000]
    version = re.search(r"plotly\.js\s+v([0-9][^\s*]*)", head)
    copyright_line = re.search(r"^\s*\*\s*(Copyright[^\n]*?)\s*$", head, re.MULTILINE)
    if not version or not copyright_line:
        raise ValueError(
            f"{PLOTLY_PATH}: could not read the version/copyright banner — has the bundle been "
            "replaced with one built without the standard header?"
        )
    return version.group(1), copyright_line.group(1)


def read_tailwind_banner() -> str | None:
    """The Tailwind version from the banner that survives minification at line 1 of app.css.

    app.css is a build artifact, so its banner is the only in-file evidence of what produced it —
    and it names Tailwind only. daisyUI contributes styles to the same file but leaves no marker,
    which is exactly why the notice cannot be built from app.css alone; package-lock.json supplies
    the rest. Returns None if the banner is absent (a Tailwind release could stop emitting it),
    in which case the notice falls back to the lock file for the version too.
    """
    first_line = APP_CSS_PATH.read_text(encoding="utf-8", errors="replace")[:400]
    match = re.search(r"tailwindcss\s+v([0-9][^\s|]*)", first_line)
    return match.group(1) if match else None


def npm_versions() -> dict[str, str]:
    """Package name → resolved version, from package-lock.json's `packages` map.

    The lock file is the resolved truth; package.json only carries `^` ranges. Keys are the bare
    package names ("daisyui"), stripped of the "node_modules/" prefix the lock uses.
    """
    data = json.loads(PACKAGE_LOCK_PATH.read_text(encoding="utf-8"))
    versions: dict[str, str] = {}
    for key, entry in data.get("packages", {}).items():
        if not key.startswith("node_modules/"):
            continue
        name = key[len("node_modules/"):]
        # Nested installs appear as "node_modules/a/node_modules/b"; only the top-level entry is
        # the version we actually built with.
        if "/node_modules/" in name:
            continue
        if isinstance(entry, dict) and "version" in entry:
            versions[name] = entry["version"]
    return versions


# ── the Python runtime set ────────────────────────────────────────────────────

def _requirement_name(specifier: str) -> str:
    """The bare distribution name from a PEP 508 requirement string.

    Only the name is needed here — the version constraint is already resolved in uv.lock — so this
    stops at the first character that can follow a name rather than parsing the full grammar.
    """
    return re.split(r"[\s\[<>=!~;(]", specifier.strip(), maxsplit=1)[0]


def runtime_packages() -> dict[str, str]:
    """The distributions bundled at runtime: name → locked version, sorted by name.

    This is the pyproject `dependencies` closure resolved through uv.lock.

    Walks uv.lock's per-package `dependencies` (and the `optional-dependencies` groups selected by
    an extra, so `uvicorn[standard]` pulls in httptools/uvloop/websockets/…) breadth-first from the
    declared runtime requirements. The `dev` dependency-group is never entered: pytest, playwright
    and httpx are test-time tools and PyInstaller does not put them in a bundle, so listing them
    would over-claim what we redistribute.

    Platform markers are deliberately NOT evaluated. uvloop is Unix-only, and pywebview drags in
    pythonnet/clr-loader/cffi on Windows and pyobjc on macOS; since releases are built for all
    three platforms, the union across platforms is the honest set for a single notice file. The
    consequence is that some listed packages are not installed on whatever machine runs this
    script — render() handles that rather than treating it as an error.

    The version comes from uv.lock rather than from the installed distribution, so it is the same
    on every machine. That is what makes the generated file byte-stable and `--check` meaningful.
    """
    lock = tomllib.loads(UV_LOCK_PATH.read_text(encoding="utf-8"))
    by_name = {entry["name"]: entry for entry in lock.get("package", [])}

    project = tomllib.loads(PYPROJECT_PATH.read_text(encoding="utf-8"))["project"]
    # (name, extras) pairs; extras select optional-dependency groups in the locked entry.
    pending: list[tuple[str, tuple[str, ...]]] = []
    for specifier in project.get("dependencies", []):
        name = _requirement_name(specifier)
        extras = re.search(r"\[([^\]]*)\]", specifier)
        pending.append((
            name,
            tuple(e.strip() for e in extras.group(1).split(",")) if extras else (),
        ))

    seen: set[tuple[str, tuple[str, ...]]] = set()
    resolved: dict[str, str] = {}
    while pending:
        name, extras = pending.pop()
        if (name, extras) in seen:
            continue
        seen.add((name, extras))
        entry = by_name.get(name)
        if entry is None:
            raise ValueError(
                f"{name!r} is a declared runtime dependency but is absent from {UV_LOCK_PATH.name}"
                " — the lock file is out of date; run `uv lock`."
            )
        resolved[name] = entry.get("version", "unknown")
        edges = list(entry.get("dependencies", []))
        optional = entry.get("optional-dependencies", {})
        for extra in extras:
            edges.extend(optional.get(extra, []))
        for edge in edges:
            pending.append((edge["name"], tuple(edge.get("extra", ()))))

    resolved.pop(PROJECT_NAME, None)
    return {name: resolved[name] for name in sorted(resolved)}


def package_license(name: str) -> str:
    """A human-readable licence for one installed distribution, or a marker if none is declared.

    Metadata is read in the order the packaging ecosystem moved through: PEP 639's
    `License-Expression` (an SPDX expression, what current builds emit), then the legacy free-text
    `License` field, then the `License ::` trove classifiers. The free-text field is truncated at
    the first line because some projects paste an entire licence into it.

    Raises PackageNotFoundError when the distribution is not installed; the caller decides what to
    do with that, because "not installed" has two very different causes — see render().
    """
    meta = metadata.distribution(name).metadata

    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()

    legacy = meta.get("License")
    if legacy and legacy.strip() and legacy.strip() != "UNKNOWN":
        return legacy.strip().splitlines()[0].strip()

    classifiers = [
        value.split("::")[-1].strip()
        for value in (meta.get_all("Classifier") or [])
        if value.startswith("License ::")
    ]
    if classifiers:
        return " / ".join(sorted(set(classifiers)))

    # Stated rather than guessed: an unlicensed-looking distribution is a thing a human must go
    # look at, and silently writing "MIT" would be a false attribution.
    return "not declared in package metadata — verify upstream"


