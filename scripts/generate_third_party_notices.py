def package_homepage(name: str) -> str:
    """The "where to get it" URL for one distribution.

    Deliberately the PyPI project page rather than whatever Home-page/Project-URL the installed
    metadata happens to declare. Two reasons: PyPI is where the wheel we actually bundle came
    from, and it is derivable from the name alone — so the column is identical no matter which
    platform generated the file, which is what keeps `--check` from failing on platform noise.
    PyPI links onward to each project's own homepage and source.
    """
    return f"https://pypi.org/project/{name}/"


